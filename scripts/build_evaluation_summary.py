"""Publish aggregate measurements only; never copy evaluation cases into the UI."""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    rag_path = ROOT / "evaluation/results/heldout.json"
    cache_path = ROOT / "docs/cache-benchmark.json"
    rag, cache = (json.loads(p.read_text()) for p in (rag_path, cache_path))
    labels = {
        "frozen_hybrid": "Frozen hybrid",
        "v2_baseline": "Production baseline",
        "query": "Query shaping (not selected)",
        "improved": "Query + diversity (experimental)",
        "rerank": "Reranker gate (rejected)",
    }
    rows = [
        {"id": key, "name": name, **rag["variants"][key]["summary"]} for key, name in labels.items()
    ]
    measurements = cache["measurements"]
    comparisons = []
    for workload in ("warm_repeated", "unique"):
        before = measurements[f"disabled/{workload}"]["p50_ms"]
        after = measurements[f"both/{workload}"]["p50_ms"]
        comparisons.append(
            {
                "workload": workload,
                "before_ms": before,
                "after_ms": after,
                "reduction_percent": (before - after) / before * 100,
                "requests_per_mode": measurements[f"both/{workload}"]["requests"],
            }
        )
    pilot_path = ROOT / "evaluation/diagnosis-v2/results/development-pilot.json"
    pilot = (
        json.loads(pilot_path.read_text())
        if pilot_path.exists()
        else {"rows": [], "calls_started": 0, "reported_tokens": 0}
    )
    pilot_summary = {
        "available": pilot_path.exists(),
        "calls_started": pilot["calls_started"],
        "reported_tokens": pilot["reported_tokens"],
        "methods": [
            {
                "method": method,
                "attempted": sum(row["method"] == method for row in pilot["rows"]),
                "valid": sum(
                    row["method"] == method and row["status"] == "structurally_valid"
                    for row in pilot["rows"]
                ),
            }
            for method in ("logs_only", "all_context", "baseline_rag")
        ],
    }
    workflow_path = ROOT / "evaluation/diagnosis-v2/results/workflow-heldout/summary.json"
    workflow_result = json.loads(workflow_path.read_text()) if workflow_path.exists() else {}
    raw_path = workflow_path.with_name("results.json")
    used_cases = (
        len({row["case_id"] for row in json.loads(raw_path.read_text())["rows"]})
        if raw_path.exists()
        else 0
    )
    workflow = {
        "available": workflow_path.exists(),
        "complete": workflow_result.get("complete", False),
        "attempted": workflow_result.get("attempted_episodes", 0),
        "planned": 52,
        "valid_reports": workflow_result.get("valid_reports", 0),
        "calls_started": workflow_result.get("calls_started", 0),
        "reported_tokens": workflow_result.get("reported_tokens", 0),
        "untouched_cases": 16 - used_cases,
    }
    return {
        "version": "measured-progress-v1",
        "study_date": "2026-11-04",
        "rag": rows,
        "cache": comparisons,
        "cache_same_results": cache["same_results"],
        "pilot": pilot_summary,
        "workflow": workflow,
        "sources": [
            {
                "path": str(p.relative_to(ROOT)).replace("\\", "/"),
                "sha256": hashlib.sha256(p.read_bytes()).hexdigest(),
            }
            for p in [
                rag_path,
                cache_path,
                *([pilot_path] if pilot_path.exists() else []),
                *([workflow_path] if workflow_path.exists() else []),
            ]
        ],
        "limits": [
            "Internal authored study; not an independent benchmark.",
            "Historical frozen measurements; not a new evaluation of this build.",
            "15 answerable and 5 absent-knowledge held-out questions; sections are relevance units.",
            "Recall is retrieval coverage, not diagnosis accuracy.",
            "Experimental recall gain came with lower MRR; production baseline retained.",
            "Cache timings are local sequential measurements on a tiny corpus; cache stays optional.",
        ],
    }


if __name__ == "__main__":
    output = ROOT / "frontend/src/evaluationSummary.ts"
    output.write_text(
        "// Generated by scripts/build_evaluation_summary.py; aggregates only.\n"
        + "export const evaluationSummary = "
        + json.dumps(build(), indent=2)
        + " as const;\n",
        encoding="utf-8",
    )
    print("Published aggregate evaluation summary; no questions, labels or provider calls.")
